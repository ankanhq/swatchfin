// Builds the animated header logos from the original brand files:
//   swatchfin-logo.svg      -> swatchfin-logo-animated.svg
//   swatchfin-logo-dark.svg -> swatchfin-logo-dark-animated.svg
// Run it with `npm run logo`. The original files are only read, never changed.
//
// In plain English:
//   1. Read the original lockup.
//   2. Find the one group that holds the three swatch cards (ink, coral, amber).
//   3. Give each card its own wrapper group, keeping its path, colour, clip
//      and mask exactly as they are, so each card can move on its own.
//   4. Add a short CSS animation inside the SVG: the coral and amber cards
//      start tucked behind the ink card and fan out around the rivet, once.
// The last frame of the animation is the original logo.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const brandDir = path.join(root, 'frontend', 'assets', 'brand');

const FILES = [
  ['swatchfin-logo.svg', 'swatchfin-logo-animated.svg'],
  ['swatchfin-logo-dark.svg', 'swatchfin-logo-dark-animated.svg'],
];

// The rivet hole the cards turn around, in the mark's own coordinates
// (taken from the <circle> in the original mask).
const RIVET = { x: 18.5, y: 45.8 };

// The cards group in the original: one <g> with the clip and mask, holding
// exactly three <path> elements in the order ink, coral, amber.
const CARDS_GROUP =
  /<g clip-path="url\(#([\w-]+)\)" mask="url\(#([\w-]+)\)">\s*(<path[^>]*\/>)\s*(<path[^>]*\/>)\s*(<path[^>]*\/>)\s*<\/g>/;

const STYLE = `<style>
    /* Fan-open animation, played once when the image loads.
       Coral and amber start turned back behind the ink card and swing
       out around the rivet. Reduced-motion visitors are never sent this
       file (see index.html), and the media query below is a second guard. */
    .sf-card--coral,
    .sf-card--amber {
      transform-box: view-box;
      transform-origin: ${RIVET.x}px ${RIVET.y}px;
      animation-duration: 600ms;
      animation-timing-function: cubic-bezier(0.2, 0.8, 0.2, 1);
      animation-delay: 150ms;
      animation-fill-mode: both;
    }
    .sf-card--coral { animation-name: sf-fan-coral; }
    .sf-card--amber { animation-name: sf-fan-amber; }
    @keyframes sf-fan-coral {
      from { opacity: 0; transform: rotate(-16deg); }
      to { opacity: 1; transform: rotate(0deg); }
    }
    @keyframes sf-fan-amber {
      from { opacity: 0; transform: rotate(-32deg); }
      to { opacity: 1; transform: rotate(0deg); }
    }
    @media (prefers-reduced-motion: reduce) {
      .sf-card--coral,
      .sf-card--amber { animation: none; }
    }
  </style>`;

/**
 * Turns one original lockup into its animated version.
 * @param {string} svg The original file's text.
 * @param {string} sourceName Used in error messages and the file comment.
 * @returns {string}
 */
function animate(svg, sourceName) {
  // Drop the content-credentials block. It describes the original file and
  // would not match the new one.
  let out = svg.replace(/<metadata>[\s\S]*?<\/metadata>/, '').replace(' xmlns:c2pa="http://c2pa.org/manifest"', '');

  const match = out.match(CARDS_GROUP);
  if (!match) throw new Error(`${sourceName}: could not find the swatch cards group`);
  const [group, clipId, maskId, ink, coral, amber] = match;

  // Check the paths are the cards we expect, so a redesigned logo fails loudly.
  if (!coral.includes('fill="#FF5A1F"') || !amber.includes('fill="#FFB020"')) {
    throw new Error(`${sourceName}: unexpected card colours`);
  }

  const card = (name, pathTag) =>
    `<g class="sf-card sf-card--${name}"><g clip-path="url(#${clipId})" mask="url(#${maskId})">${pathTag}</g></g>`;

  // Ink is drawn last, so the other two cards start hidden behind it.
  // In the final frame no card overlaps another, so the order changes nothing.
  const cards = [card('amber', amber), card('coral', coral), card('ink', ink)].join('\n  ');
  out = out.replace(group, cards);

  if (!out.includes('<title>Swatchfin</title>')) throw new Error(`${sourceName}: missing <title>`);
  out = out.replace(
    '<title>Swatchfin</title>',
    `<title>Swatchfin</title>\n  <!-- Generated by tools/build-animated-logo.mjs from ${sourceName}. Do not edit by hand. -->\n  ${STYLE}`,
  );
  return out;
}

async function main() {
  for (const [source, target] of FILES) {
    const svg = await readFile(path.join(brandDir, source), 'utf8');
    const result = animate(svg, source);
    await writeFile(path.join(brandDir, target), result);
    console.log(`${target}: ${result.length} bytes (from ${source})`);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
